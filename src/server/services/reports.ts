// CSV report generation. Rows come from the same scoped queries as the on-screen lists, totals are
// computed from those rows, and every export is recorded in the audit trail.
import type { Prisma } from "@prisma/client";
import { prisma } from "../db";
import type { Actor } from "../auth/actor";
import { instrumentScope, releaseScope, requirePermission } from "../auth/scope";
import { recordAudit } from "../audit";
import { getSettings } from "../settings";
import { buildInstrumentWhere, instrumentOrderBy, type InstrumentFilters } from "./search";
import { ValidationError } from "../errors";
import { addDays, businessToday, daysBetween, maturityState, toDateOnlyString } from "@/lib/dates";
import { now } from "../clock";

const MAX_ROWS = 10_000;

/** Escape a CSV cell and neutralise spreadsheet formula injection (=, +, -, @, tab, CR). */
export function csvCell(value: unknown): string {
  if (value === null || value === undefined) return "";
  let s = value instanceof Date ? value.toISOString() : String(value);
  if (/^[=+\-@\t\r]/.test(s) && !/^-?\d+(\.\d+)?$/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function toCsv(headers: string[], rows: unknown[][], footer: unknown[][] = []): string {
  const lines = [headers, ...rows, ...(footer.length ? [[], ...footer] : [])].map((r) => r.map(csvCell).join(","));
  return "﻿" + lines.join("\r\n") + "\r\n"; // BOM so spreadsheet apps detect UTF-8 (₹)
}

/** Sum money values in integer paise to avoid floating-point drift. */
const sumDecimal = (values: ({ toString(): string } | null)[]) =>
  values.reduce<number>((acc, v) => acc + (v ? Math.round(Number(v.toString()) * 100) : 0), 0) / 100;

export const REPORTS = {
  "instrument-register": { title: "Instrument register", permission: "report:export" },
  "maturity-schedule": { title: "Maturity schedule (next 180 days and matured)", permission: "report:export" },
  "release-requests": { title: "Release / refund requests", permission: "report:export" },
  discrepancies: { title: "Open discrepancies", permission: "report:export" },
  "audit-log": { title: "Audit log", permission: "audit:export" },
} as const;
export type ReportKind = keyof typeof REPORTS;

export async function generateReport(actor: Actor, kind: string, filters: InstrumentFilters & { from?: string; to?: string }) {
  if (!(kind in REPORTS)) throw new ValidationError("Unknown report.");
  const report = REPORTS[kind as ReportKind];
  requirePermission(actor, report.permission);
  const settings = await getSettings();
  const nowTs = now();
  const today = businessToday(nowTs);
  let csv: string;
  let rowCount: number;
  const generated = [["Generated", nowTs.toISOString()], ["Generated by", `${actor.name} (${actor.role})`], ["Note", "Contains synthetic demonstration data where marked; values are as recorded in the portal."]];

  switch (kind as ReportKind) {
    case "instrument-register":
    case "maturity-schedule": {
      let where = buildInstrumentWhere(actor, filters, settings, nowTs);
      if (kind === "maturity-schedule") where = { AND: [where, { status: "ACCEPTED", maturityDate: { lte: addDays(today, 180) } }] };
      const rows = await prisma.instrument.findMany({
        where,
        orderBy: kind === "maturity-schedule" ? [{ maturityDate: "asc" }] : instrumentOrderBy(filters),
        include: { institution: { select: { name: true, code: true } }, _count: { select: { discrepancies: { where: { status: "OPEN" } } } } },
        take: MAX_ROWS,
      });
      rowCount = rows.length;
      csv = toCsv(
        ["Reference", "Institution code", "Institution", "Type", "Instrument number", "Bank", "Branch", "IFSC", "Amount (INR)", "Issue date", "Maturity date", "Days to maturity", "Maturity state", "Status", "Verification", "Open discrepancies", "Origin", "Demo data"],
        rows.map((r) => [
          r.referenceNo, r.institution.code, r.institution.name, r.type, r.instrumentNumber, r.bankName, r.branchName, r.ifscCode,
          r.amount?.toFixed(2), toDateOnlyString(r.issueDate), toDateOnlyString(r.maturityDate),
          r.maturityDate ? daysBetween(today, r.maturityDate) : "", maturityState(r.maturityDate, today, settings.expiringSoonDays),
          r.status, r.verificationStatus, r._count.discrepancies, r.origin, r.isDemo ? "YES" : "NO",
        ]),
        [["Total records", rows.length], ["Total amount (INR)", sumDecimal(rows.map((r) => r.amount)).toFixed(2)], ...generated],
      );
      break;
    }
    case "release-requests": {
      const statuses = ["SUBMITTED", "UNDER_SCRUTINY", "INFO_REQUESTED", "PENDING_APPROVAL", "APPROVED", "REJECTED", "COMPLETED", "WITHDRAWN"];
      const status = filters.status && statuses.includes(filters.status) ? { status: filters.status as "SUBMITTED" } : {};
      const where: Prisma.ReleaseRequestWhereInput = { AND: [releaseScope(actor), status] };
      const rows = await prisma.releaseRequest.findMany({
        where,
        orderBy: { submittedAt: "desc" },
        include: { institution: { select: { name: true, code: true } }, instrument: { select: { referenceNo: true, instrumentNumber: true } } },
        take: MAX_ROWS,
      });
      rowCount = rows.length;
      csv = toCsv(
        ["Request", "Institution code", "Institution", "Instrument", "Instrument number", "Type", "Requested amount (INR)", "Status", "Submitted", "Decision", "Decision reason", "Decided at", "Completion reference", "Completed at"],
        rows.map((r) => [
          r.referenceNo, r.institution.code, r.institution.name, r.instrument.referenceNo, r.instrument.instrumentNumber, r.type,
          r.requestedAmount.toFixed(2), r.status, r.submittedAt, r.decision, r.decisionReason, r.decidedAt, r.completionReference, r.completedAt,
        ]),
        [["Total requests", rows.length], ["Total requested (INR)", sumDecimal(rows.map((r) => r.requestedAmount)).toFixed(2)], ...generated],
      );
      break;
    }
    case "discrepancies": {
      const rows = await prisma.discrepancy.findMany({
        where: { status: "OPEN", instrument: instrumentScope(actor) },
        orderBy: [{ severity: "asc" }, { raisedAt: "asc" }],
        include: { instrument: { select: { referenceNo: true, status: true, institution: { select: { code: true, name: true } } } } },
        take: MAX_ROWS,
      });
      rowCount = rows.length;
      csv = toCsv(
        ["Instrument", "Institution code", "Institution", "Instrument status", "Code", "Severity", "Source", "Message", "Raised at"],
        rows.map((d) => [d.instrument?.referenceNo, d.instrument?.institution.code, d.instrument?.institution.name, d.instrument?.status, d.code, d.severity, d.source, d.message, d.raisedAt]),
        [["Total open discrepancies", rows.length], ...generated],
      );
      break;
    }
    case "audit-log": {
      const where: Prisma.AuditEventWhereInput = {};
      const from = filters.from ? new Date(filters.from) : null;
      const to = filters.to ? new Date(filters.to) : null;
      if ((from && !Number.isNaN(from.getTime())) || (to && !Number.isNaN(to.getTime()))) {
        where.createdAt = { ...(from && !Number.isNaN(from.getTime()) ? { gte: from } : {}), ...(to && !Number.isNaN(to.getTime()) ? { lte: to } : {}) };
      }
      const rows = await prisma.auditEvent.findMany({ where, orderBy: { id: "desc" }, take: MAX_ROWS });
      rowCount = rows.length;
      csv = toCsv(
        ["Event ID", "Timestamp", "Actor", "Actor role", "Action", "Resource type", "Resource ID", "Institution ID", "Reason", "Before", "After", "Correlation ID"],
        rows.map((e) => [e.id.toString(), e.createdAt, e.actorLabel, e.actorRole, e.action, e.resourceType, e.resourceId, e.institutionId, e.reason, e.before ? JSON.stringify(e.before) : "", e.after ? JSON.stringify(e.after) : "", e.correlationId]),
        [["Total events", rows.length], ...generated],
      );
      break;
    }
  }

  await recordAudit(prisma, actor, {
    action: "REPORT_EXPORTED",
    resourceType: "Report",
    resourceId: kind,
    after: { rowCount, filters, truncated: rowCount >= MAX_ROWS },
  });
  return { csv, filename: `${kind}-${toDateOnlyString(today)}.csv` };
}
